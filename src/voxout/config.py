COVERAGE_MIN = 0.97
"""闸门 1：ASR 汉字覆盖率下限。

T13 在两篇真实短帖上重新读数（整篇一次转写，即闸门实际的量法），每篇两次独立生成：

    213 汉字   99.06%  99.06%
    540 汉字   98.89%  97.96%

原标定（设计 §3 的 98.4–98.9%）用的是 numeral-free 语料，本轮换了 ASR 参数并给
比较加了双侧数字归一化与繁转简，读数因此重测——**结论是阈值不动**。

余量按最差那次算是 0.96 个百分点，不是首轮那次的 1.89——同一篇帖子换一次生成就
差了 0.93 个百分点，拿运气好的那次报余量与 n=1 基线是同一种错。之所以仍然守住
0.97 而不下调：真丢内容的读数离这里很远（T13a 实测单段送出 213/540 汉字是
55.40%/85.00%，边缘的 78 汉字是 97.44%），噪声侧聚在 98–99%，两侧之间是一段空白。
阈值放在 0.97 距噪声侧最差读数 0.96 点、距真丢内容侧 12 点以上。

下调的触发条件写在这里，免得下次凭印象决定：**某次读数低于 97%，且音频经人工听审
确认完整**（秒每汉字落在 0.20–0.26 的正常带内只是旁证，不能替代听审）。满足这两条
才把阈值与理由一并更新——不许「调阈值让它过」而不写原因（lessons.md #1）。

还有一处值得记下：540 汉字那篇逐段转写再按汉字加权是 97.59%，整篇一次转写是
98.89%。整篇转写的上下文更长，ASR 反而更准，所以按段设闸门只会更严而不是更准。"""

VOICE_DRIFT_MAX_PCT = 15.0
